/// Phrases in one call, since every event needs the same two kinds.
fn phrases(examples_en: &[&str], examples_uk: &[&str], commands: &[&str]) -> Vec<Phrase> {
    examples_en
        .iter()
        .map(|t| Phrase::example(Lang::En, t))
        .chain(examples_uk.iter().map(|t| Phrase::example(Lang::Uk, t)))
        .chain(commands.iter().map(|t| Phrase::command(t)))
        .collect()
}

