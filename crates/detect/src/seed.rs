//! The events the application ships with.
//!
//! Thirty-six events, in Ukrainian and English, covering environment, combat, weather,
//! creatures, magic and items.
//!
//! These are a starting point, not a fixed set — the editor can change all of it, and
//! anything a person edits stops being overwritten from here.
//!
//! # Writing a term list
//!
//! Coverage is the entire job. A verb the narrator says and this file does not list is a
//! sound that never plays, and there is no feedback at the table telling anyone why. So
//! each list aims to hold *every* ordinary way its event gets described — and nothing
//! that describes something else.
//!
//! Two rules make that tractable:
//!
//! * **List lexemes, not inflections.** The stemmer strips endings, so `гарчить` covers
//!   `гарчиш`, `гарчимо`, `гарчите`. It cannot cover `загарчав`: Ukrainian aspect and
//!   prefixes change the stem itself, so every prefixed and perfective form is its own
//!   entry. This is why the lists look repetitive — `відчиняє`, `прочиняє`, `розчиняє`,
//!   `відкриває` are four different words to a stemmer, and all four get said.
//! * **Never share a verb between events whose objects can co-occur.** `б'є` belongs to
//!   the sword, not to breaking glass, because "б'є мечем по склу" must not be ambiguous.
//!   Where two events do share a verb — `вдарила` for both lightning and a sword — the
//!   keyword tells them apart, and the action gate needs both to fire.

