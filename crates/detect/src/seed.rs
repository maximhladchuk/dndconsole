#[cfg(test)]
mod tests {
    use super::*;
    use crate::event::EventKind;
    use std::collections::HashSet;

    #[test]
    fn the_seed_set_covers_the_events_the_spec_asks_for() {
        let ids: HashSet<String> = seed_events().into_iter().map(|e| e.id).collect();

        for expected in [
            "OPEN_DOOR",
            "DOOR_SLAM",
            "CHEST_OPEN",
            "SWORD_SWING",
            "BOW_SHOT",
            "THUNDER",
            "FIRE",
            "WATER_SPLASH",
            "WOLF_GROWL",
            "SMALL_CREATURE_SCURRY",
            "FOOTSTEPS",
            "MAGIC_CAST",
            "COINS",
            "GLASS_SHATTER",
        ] {
            assert!(ids.contains(expected), "missing {expected}");
        }
    }

    #[test]
    fn every_seed_event_is_usable_as_shipped() {
        for event in seed_events() {
            assert!(!event.id.is_empty());
            assert!(!event.display_name.is_empty());
            assert!(!event.category.is_empty(), "{} has no category", event.id);
            assert!(event.enabled);
            assert_eq!(event.kind, EventKind::OneShot);

            assert!(
                event.examples().count() >= 4,
                "{} needs enough phrasings to be useful",
                event.id
            );
            assert!(
                event.commands().count() >= 1,
                "{} should have a spoken command",
                event.id
            );
            assert!(
                (0.75..=0.95).contains(&event.confidence_threshold),
                "{} has an implausible threshold",
                event.id
            );
            assert!(
                event.cooldown_ms >= 1_000,
                "{} would retrigger too fast",
                event.id
            );
        }
    }

    #[test]
    fn every_seed_event_has_phrases_in_both_languages() {
        for event in seed_events() {
            let languages: HashSet<Lang> = event.examples().map(|phrase| phrase.lang).collect();
            assert!(
                languages.contains(&Lang::En) && languages.contains(&Lang::Uk),
                "{} is missing a language",
                event.id
            );
        }
    }

    #[test]
    fn events_that_can_be_described_without_happening_have_action_words() {
        // A sword can lie on a table; thunder cannot lie on a table. Anything whose
        // object can be mentioned passively needs the action gate.
        for event in seed_events() {
            if event.require_action_word {
                assert!(
                    event.terms_of(crate::event::TermKind::Action).count() >= 3,
                    "{} gates on action words but barely lists any",
                    event.id
                );
            }
        }
    }
}
